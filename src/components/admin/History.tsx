import React, { useEffect, useState } from 'react';
import { Calendar, Download, FileText, Train, Ship, Clock, CheckCircle } from 'lucide-react';
import { supabase, OperationalPlan } from '../../lib/supabase';

export const History: React.FC<{
  onNotification: (type: 'success' | 'error' | 'info', message: string) => void;
}> = ({ onNotification }) => {
  const [plans, setPlans] = useState<OperationalPlan[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    loadHistory();
  }, []);

  const loadHistory = async () => {
    try {
      const thirtyDaysAgo = new Date();
      thirtyDaysAgo.setDate(thirtyDaysAgo.getDate() - 30);

      const { data, error } = await supabase
        .from('operational_plans')
        .select('*')
        .eq('status', 'sent')
        .gte('created_at', thirtyDaysAgo.toISOString())
        .order('created_at', { ascending: false });

      if (error) throw error;
      if (data) setPlans(data);
    } catch (err) {
      console.error('Error loading history:', err);
    } finally {
      setLoading(false);
    }
  };

  const downloadPDF = (plan: OperationalPlan) => {
    const d = plan.plan_data;
    const metroAssignments: any[] = d?.metro_trains?.assignments ?? [];
    const waterAssignments: any[] = d?.water_boats?.assignments ?? [];

    const formatAssignments = (list: any[]) => {
      if (!list.length) return '  (none)\n';
      return list.map(a => `  • ${a.vehicle_number} (${a.vehicle_name}) — ${a.status}${a.manually_edited ? ' [admin edited]' : ''}`).join('\n') + '\n';
    };

    const content = [
      '================================================================',
      '            KO-NECT OPERATIONAL PLAN REPORT',
      '================================================================',
      '',
      `Report Date : ${new Date(plan.plan_date).toLocaleDateString('en-IN', { weekday: 'long', day: '2-digit', month: 'long', year: 'numeric' })}`,
      `Approved At : ${new Date(plan.approved_at || plan.created_at).toLocaleString()}`,
      `Plan ID     : ${plan.id}`,
      `AI Confidence: ${plan.ai_confidence.toFixed(1)}%`,
      `Manual Overrides: ${d?.total_manual_overrides ?? 0}`,
      '',
      '----------------------------------------------------------------',
      '  METRO TRAINS SUMMARY',
      '----------------------------------------------------------------',
      `  Total Trains   : ${d?.metro_trains?.total ?? 0}`,
      `  In Service     : ${d?.metro_trains?.service ?? 0}`,
      `  In Maintenance : ${d?.metro_trains?.maintenance ?? 0}`,
      `  Standby/Ready  : ${d?.metro_trains?.standby ?? 0}`,
      '',
      '  SERVICE:',
      formatAssignments(metroAssignments.filter((a: any) => a.status === 'service')),
      '  MAINTENANCE:',
      formatAssignments(metroAssignments.filter((a: any) => a.status === 'maintenance')),
      '  STANDBY/READY:',
      formatAssignments(metroAssignments.filter((a: any) => a.status === 'standby' || a.status === 'ready')),
      '',
      '----------------------------------------------------------------',
      '  WATER METRO BOATS SUMMARY',
      '----------------------------------------------------------------',
      `  Total Boats    : ${d?.water_boats?.total ?? 0}`,
      `  In Service     : ${d?.water_boats?.service ?? 0}`,
      `  In Maintenance : ${d?.water_boats?.maintenance ?? 0}`,
      `  Standby/Ready  : ${d?.water_boats?.standby ?? 0}`,
      '',
      '  SERVICE:',
      formatAssignments(waterAssignments.filter((a: any) => a.status === 'service')),
      '  MAINTENANCE:',
      formatAssignments(waterAssignments.filter((a: any) => a.status === 'maintenance')),
      '  STANDBY/READY:',
      formatAssignments(waterAssignments.filter((a: any) => a.status === 'standby' || a.status === 'ready')),
      '',
      '================================================================',
      '  Generated by KO-NECT AI Operations Control System',
      `  Downloaded: ${new Date().toLocaleString()}`,
      '================================================================',
    ].join('\n');

    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `KONECT-Plan-${plan.plan_date}-${plan.id.slice(0, 8)}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    onNotification('success', 'Report downloaded successfully');
  };

  if (loading) {
    return (
      <div className="flex items-center justify-center h-full">
        <div className="animate-spin rounded-full h-10 w-10 border-b-2 border-blue-600" />
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div>
        <h2 className="text-2xl font-bold text-gray-900">Operational History</h2>
        <p className="text-gray-500 mt-0.5 text-sm">Last 30 days of approved operational plans — downloadable reports</p>
      </div>

      <div className="bg-blue-50 border-l-4 border-blue-600 p-4 rounded-lg flex items-start gap-3">
        <FileText className="w-5 h-5 text-blue-600 flex-shrink-0 mt-0.5" />
        <div>
          <div className="font-medium text-blue-900">30-Day Archive</div>
          <div className="text-sm text-blue-700">All approved plans with full vehicle assignments available for download</div>
        </div>
      </div>

      {plans.length === 0 ? (
        <div className="bg-gray-50 border border-gray-200 rounded-xl p-12 text-center">
          <FileText className="w-12 h-12 text-gray-300 mx-auto mb-3" />
          <p className="text-gray-600 font-medium">No approved plans in the last 30 days</p>
          <p className="text-gray-400 text-sm mt-1">Plans will appear here after admin approves operational plans</p>
        </div>
      ) : (
        <div className="bg-white rounded-xl shadow-sm border border-gray-200 overflow-hidden">
          <div className="overflow-x-auto">
            <table className="w-full">
              <thead className="bg-gray-50 border-b border-gray-100">
                <tr>
                  <th className="px-5 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Date</th>
                  <th className="px-5 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Metro Trains</th>
                  <th className="px-5 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Water Boats</th>
                  <th className="px-5 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">AI Score</th>
                  <th className="px-5 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Approved At</th>
                  <th className="px-5 py-3 text-left text-xs font-semibold text-gray-500 uppercase tracking-wide">Actions</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-gray-100">
                {plans.map(plan => (
                  <tr key={plan.id} className="hover:bg-gray-50 transition">
                    <td className="px-5 py-4">
                      <div className="flex items-center gap-2">
                        <Calendar className="w-4 h-4 text-gray-400" />
                        <span className="font-medium text-gray-900">
                          {new Date(plan.plan_date).toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' })}
                        </span>
                      </div>
                    </td>
                    <td className="px-5 py-4">
                      <div className="flex items-center gap-2">
                        <Train className="w-3.5 h-3.5 text-blue-500" />
                        <span className="text-sm text-gray-700">
                          <span className="font-semibold text-green-600">{plan.plan_data?.metro_trains?.service ?? 0}</span>
                          <span className="text-gray-400"> svc · </span>
                          <span className="font-semibold text-red-600">{plan.plan_data?.metro_trains?.maintenance ?? 0}</span>
                          <span className="text-gray-400"> mnt · </span>
                          <span className="font-semibold text-gray-600">{plan.plan_data?.metro_trains?.standby ?? 0}</span>
                          <span className="text-gray-400"> stby</span>
                        </span>
                      </div>
                    </td>
                    <td className="px-5 py-4">
                      <div className="flex items-center gap-2">
                        <Ship className="w-3.5 h-3.5 text-cyan-500" />
                        <span className="text-sm text-gray-700">
                          <span className="font-semibold text-green-600">{plan.plan_data?.water_boats?.service ?? 0}</span>
                          <span className="text-gray-400"> svc · </span>
                          <span className="font-semibold text-red-600">{plan.plan_data?.water_boats?.maintenance ?? 0}</span>
                          <span className="text-gray-400"> mnt · </span>
                          <span className="font-semibold text-gray-600">{plan.plan_data?.water_boats?.standby ?? 0}</span>
                          <span className="text-gray-400"> stby</span>
                        </span>
                      </div>
                    </td>
                    <td className="px-5 py-4">
                      <span className="text-sm font-semibold text-gray-700">{plan.ai_confidence.toFixed(1)}%</span>
                    </td>
                    <td className="px-5 py-4">
                      <div className="flex items-center gap-1.5 text-sm text-gray-500">
                        <Clock className="w-3.5 h-3.5 text-gray-400" />
                        {new Date(plan.approved_at || plan.created_at).toLocaleString()}
                      </div>
                    </td>
                    <td className="px-5 py-4">
                      <div className="flex items-center gap-3">
                        <span className="flex items-center gap-1 text-xs text-green-600 font-medium">
                          <CheckCircle className="w-3 h-3" /> Delivered
                        </span>
                        <button
                          onClick={() => downloadPDF(plan)}
                          className="flex items-center gap-1.5 text-blue-600 hover:text-blue-700 font-medium text-sm transition"
                        >
                          <Download className="w-3.5 h-3.5" />
                          Download
                        </button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      <p className="text-sm text-gray-400">{plans.length} approved plan{plans.length !== 1 ? 's' : ''} in the last 30 days</p>
    </div>
  );
};
